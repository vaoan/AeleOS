/**
 * Fails when a directory's agent note went unread while its code changed.
 *
 * `check-doc-freshness.mjs` compares an exported symbol against its own TSDoc,
 * which is per symbol and structurally blind to a note whose subject is a
 * different file — a deleted prop, a mechanism that moved, a debt that was
 * paid. Root rule 18 names that exposure and root rule 30 is what it cost.
 * `apps/hub/src/features/actors/CLAUDE.md` already opens with a standing rule
 * requiring a re-read on every change inside that folder; nothing enforced it.
 *
 * The rule is generic, so a note written tomorrow is guarded the same way:
 * every `CLAUDE.md` and `AGENTS.md` in the repository governs the directory it
 * sits in, and a change under it must be accompanied by a change to it.
 *
 * Two mechanical exemptions, neither of them a maintained list:
 *
 * - A **pointer** carries no prose of its own — `apps/hub/CLAUDE.md` is the
 *   eleven bytes `@AGENTS.md`. Demanding an edit to it would be demanding a
 *   ritual.
 * - A **vendored** file is generated by somebody else between BEGIN/END
 *   markers, and `apps/hub/AGENTS.md` is Next.js's own agent rules. Nobody
 *   here may edit it, so it cannot be what a gate demands.
 *
 * **A skipped note does not hand its subtree up to the note above it.** That
 * is the ruling this gate is built on rather than an oversight. Falling
 * through would put every change under `apps/hub` on the root `CLAUDE.md`,
 * which is 118KB of running record — and a gate that fires on a workflow tweak
 * is one people satisfy with a blank line. The cost is that such a subtree is
 * unguarded, so the run PRINTS what it skipped: the fix is to write a real
 * note there, not to bend the rule.
 *
 * There is no suppression flag, matching its sibling and for the same reason:
 * a suppression flag becomes the thing everyone types. The way past it is to
 * re-read the note, and restating something that still holds is itself worth
 * writing.
 *
 * Usage:
 *   node scripts/check-agent-notes.mjs [baseRef]   compare baseRef...HEAD
 *   node scripts/check-agent-notes.mjs --staged    compare HEAD to the index
 */
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";

/** Everything a generator owns, markers included. */
const VENDORED_BLOCK = /<!--\s*BEGIN:[^>]*-->[\s\S]*?<!--\s*END:[^>]*-->/g;

/** The file names that make a directory governed. */
const NOTE_NAMES = new Set(["CLAUDE.md", "AGENTS.md"]);

/**
 * What kind of file a note is, which decides whether it governs anything.
 *
 * @param text - the note's full contents.
 * @returns `"note"` for prose somebody here maintains, `"pointer"` for a file
 *   that is only `@import` lines, `"vendored"` for one that is wholly
 *   generated, and `"empty"` for one with nothing in it.
 */
export function classifyNote(text) {
  if (text.trim() === "") return "empty";

  const stripped = text.replace(VENDORED_BLOCK, "");
  // Only when the generated block was ALL of it. Prose beside one is prose.
  if (stripped.trim() === "") return "vendored";

  const lines = stripped.split("\n").filter((line) => line.trim() !== "");
  return lines.every((line) => line.trimStart().startsWith("@"))
    ? "pointer"
    : "note";
}

/**
 * The directory a repository-relative path sits in, with the root as `""`.
 *
 * @param file - a slash-separated repository-relative path.
 * @returns the directory key used throughout this gate.
 */
function dirKey(file) {
  const dir = path.posix.dirname(file);
  return dir === "." ? "" : dir;
}

/**
 * Which note governs each directory that holds one.
 *
 * A directory may hold both names — `apps/hub` does — so the hand-written one
 * wins, and a directory whose notes are all skippable is kept rather than
 * dropped, because the walk has to stop there rather than continue upward.
 *
 * @param paths - every note file in the repository.
 * @param read - how to read one, given its path.
 * @returns a map from directory key to the note that decides it.
 */
export function noteIndex(paths, read) {
  const index = new Map();
  for (const notePath of [...paths].sort()) {
    const kind = classifyNote(read(notePath));
    const key = dirKey(notePath);
    const held = index.get(key);
    if (held === undefined || (held.kind !== "note" && kind === "note")) {
      index.set(key, { path: notePath, kind });
    }
  }
  return index;
}

/**
 * The note governing one file, or nothing when none does.
 *
 * @param file - a repository-relative path.
 * @param index - the map {@link noteIndex} built.
 * @returns the governing entry, or null when the nearest note is skippable or
 *   there is no note above the file at all.
 */
function governing(file, index) {
  let key = dirKey(file);
  for (;;) {
    const held = index.get(key);
    if (held !== undefined) return held.kind === "note" ? held : null;
    if (key === "") return null;
    key = dirKey(key);
  }
}

/**
 * Which notes a set of changes left unread.
 *
 * Notes are never governed by other notes: editing a note demands nothing of
 * the note above it, or every change would eventually reach the root.
 *
 * @param changed - every path the comparison reports, deletions included.
 * @param index - the map {@link noteIndex} built.
 * @returns the stale notes with the files that demanded each, and the changed
 *   paths no note governs.
 */
export function auditChanges(changed, index) {
  const seen = new Set(changed);
  const notes = new Set([...index.values()].map((held) => held.path));
  const owed = new Map();
  const ungoverned = [];

  for (const file of changed) {
    if (notes.has(file)) continue;
    const held = governing(file, index);
    if (held === null) {
      ungoverned.push(file);
      continue;
    }
    const already = owed.get(held.path);
    if (already === undefined) owed.set(held.path, [file]);
    else already.push(file);
  }

  const stale = [...owed.entries()]
    .filter(([note]) => !seen.has(note))
    .map(([note, files]) => ({ note, files: files.sort() }))
    .sort((a, b) => a.note.localeCompare(b.note));

  return { stale, ungoverned: ungoverned.sort() };
}

/**
 * Every note file git would let reach a commit.
 *
 * `git ls-files` rather than a crawl, for the reason root rule 32 records: a
 * hand-maintained skip list drifts from `.gitignore` and makes the file set
 * depend on which machine is asking.
 *
 * @param cwd - the repository to ask.
 * @returns repository-relative note paths.
 */
export function notePaths(cwd = process.cwd()) {
  const out = execFileSync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard"],
    { cwd, encoding: "utf8" },
  );
  return out
    .split("\n")
    .filter((line) => line !== "" && NOTE_NAMES.has(path.posix.basename(line)));
}

/**
 * What changed, either across a branch or in the index.
 *
 * @param cwd - the repository to ask.
 * @param baseRef - the ref to compare against, or `"--staged"`.
 * @returns repository-relative paths, deletions included.
 */
export function changedPaths(cwd, baseRef) {
  const args =
    baseRef === "--staged"
      ? ["diff", "--cached", "--name-only"]
      : ["diff", "--name-only", `${baseRef}...HEAD`];
  return execFileSync("git", args, { cwd, encoding: "utf8" })
    .split("\n")
    .filter((line) => line !== "");
}

/** What a failing run tells somebody to actually do. */
const THE_THREE_QUESTIONS = [
  "  1. Is anything in it now false? A component that no longer exists, a prop",
  "     deleted, a mechanism replaced, a number measured before this change.",
  "  2. Is anything still true but no longer how we work? Say the new way; do",
  "     not leave both — a note contradicting itself is worse than a wrong one.",
  "  3. Did this change establish something the next person needs? A trap you",
  "     fell into, a reason a tempting alternative is wrong.",
  "",
  "  Restating something that still holds counts. There is no suppression flag.",
];

/**
 * Runs the gate over a repository.
 *
 * @param cwd - the repository to check.
 * @param baseRef - the ref to compare against, or `"--staged"`.
 * @returns the process exit code.
 */
export function run(cwd, baseRef) {
  const index = noteIndex(notePaths(cwd), (file) =>
    readFileSync(path.join(cwd, file), "utf8"),
  );
  const { stale, ungoverned } = auditChanges(changedPaths(cwd, baseRef), index);

  if (ungoverned.length > 0) {
    const dirs = [...new Set(ungoverned.map((file) => dirKey(file)))].sort();
    console.log(
      `check:agent-notes — ${ungoverned.length} changed file(s) under no note, across ${dirs.length} directory(ies).`,
    );
    console.log(
      "  Not a failure. To guard a subtree, write a note in it — see this gate's own header.",
    );
  }

  if (stale.length === 0) {
    console.log("check:agent-notes — every note beside a change was re-read.");
    return 0;
  }

  for (const { note, files } of stale) {
    console.error(`\n${note} was not re-read, but these changed beneath it:`);
    for (const file of files.slice(0, 10)) console.error(`  ${file}`);
    if (files.length > 10) console.error(`  …and ${files.length - 10} more`);
  }
  console.error("\nRe-read each note against what you just did:");
  for (const line of THE_THREE_QUESTIONS) console.error(line);
  return 1;
}

if (import.meta.filename === process.argv[1]) {
  process.exitCode = run(process.cwd(), process.argv[2] ?? "origin/main");
}
